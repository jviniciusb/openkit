import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const skill = skills.find((s) => s.id === "using-git-worktrees")

test("using-git-worktrees is registered and model-visible", () => {
  expect(skill).toBeDefined()
  expect(skill!.autoinvoke).toBeUndefined()
})

test("using-git-worktrees SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", skill!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("using-git-worktrees")
  expect(frontmatter.description).toBeTruthy()
})

test("using-git-worktrees loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(skill!)
  expect(info.name).toBe("using-git-worktrees")
  expect(info.content).toContain("# Using Git Worktrees")
  expect(info.content).not.toContain("name: using-git-worktrees")
})

test("using-git-worktrees body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(skill!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/using-git-worktrees/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("using-git-worktrees keeps the isolation, gitignore, and submodule guards", () => {
  const body = loadSkill(skill!).content
  expect(body).toContain("gitignored")
  expect(body).toContain("git check-ignore")
  expect(body).toContain("--show-superproject-working-tree")
  expect(body).toContain("worktree_create")
  expect(body).toContain("session_move")
})
