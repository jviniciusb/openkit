import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const prototype = skills.find((s) => s.id === "prototype")

test("prototype is registered and model-visible", () => {
  expect(prototype).toBeDefined()
  expect(prototype!.autoinvoke).toBeUndefined()
})

test("prototype SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", prototype!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("prototype")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("prototype loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(prototype!)
  expect(info.name).toBe("prototype")
  expect(info.content).toContain("# Prototype")
  expect(info.content).not.toContain("name: prototype")
})

test("prototype body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(prototype!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/prototype/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})
