import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const skill = skills.find((s) => s.id === "improve-codebase-architecture")

test("improve-codebase-architecture is registered with autoinvoke:false", () => {
  expect(skill).toBeDefined()
  expect(skill!.autoinvoke).toBe(false)
})

test("improve-codebase-architecture SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", skill!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("improve-codebase-architecture")
  expect(frontmatter.description).toBeTruthy()
})

test("improve-codebase-architecture loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(skill!)
  expect(info.name).toBe("improve-codebase-architecture")
  expect(info.content).toContain("# Improve Codebase Architecture")
  expect(info.content).not.toContain("name: improve-codebase-architecture")
})

test("improve-codebase-architecture body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(skill!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/improve-codebase-architecture/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("improve-codebase-architecture stays read-only", () => {
  const body = loadSkill(skill!).content
  expect(body).toContain("read-only")
  expect(body).toContain("never auto-refactor")
})
