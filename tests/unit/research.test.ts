import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const research = skills.find((s) => s.id === "research")

test("research is registered and model-visible", () => {
  expect(research).toBeDefined()
  expect(research!.autoinvoke).toBeUndefined()
})

test("research SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", research!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("research")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("research loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(research!)
  expect(info.name).toBe("research")
  expect(info.content).toContain("# Research")
  expect(info.content).not.toContain("name: research")
})

test("research body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(research!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/research/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})
