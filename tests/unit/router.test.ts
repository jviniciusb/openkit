import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const router = skills.find((s) => s.id === "router")

test("router is registered and user-invoked", () => {
  expect(router).toBeDefined()
  expect(router!.autoinvoke).toBe(false)
})

test("router SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", router!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("router")
  expect(frontmatter.description).toBeTruthy()
})

test("router loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(router!)
  expect(info.name).toBe("router")
  expect(info.content).toContain("# Router")
  expect(info.content).not.toContain("name: router")
})

test("router body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(router!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/ask-matt/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("router names real kit skill ids and stays a pointer", () => {
  const body = loadSkill(router!).content
  expect(body).toContain("@sdd-flow")
  expect(body).toContain("@router")
})

test("router skill-list @id tokens all exist in the skills barrel", () => {
  const body = loadSkill(router!).content
  const ids = [...body.matchAll(/^- `@([a-z0-9-]+)`/gm)].map((m) => m[1]!)
  expect(ids.length).toBeGreaterThan(0)
  const known = new Set(skills.map((s) => s.id))
  for (const id of ids) {
    expect(known.has(id)).toBe(true)
  }
})
