import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const wizard = skills.find((s) => s.id === "wizard")

test("wizard is registered and model-visible", () => {
  expect(wizard).toBeDefined()
  expect(wizard!.autoinvoke).toBeUndefined()
})

test("wizard SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", wizard!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("wizard")
  expect(frontmatter.description).toBeTruthy()
})

test("wizard loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(wizard!)
  expect(info.name).toBe("wizard")
  expect(info.content).toContain("# Wizard")
  expect(info.content).not.toContain("name: wizard")
})

test("wizard body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(wizard!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/wizard/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("wizard body states the no-secret rule", () => {
  const body = loadSkill(wizard!).content
  expect(body).toContain("secret")
  expect(body).toContain("Never hardcode or echo a secret")
})
