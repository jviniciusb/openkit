import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const diagnosingBugs = skills.find((s) => s.id === "diagnosing-bugs")

test("diagnosing-bugs is registered and model-visible", () => {
  expect(diagnosingBugs).toBeDefined()
  expect(diagnosingBugs!.autoinvoke).toBeUndefined()
})

test("diagnosing-bugs SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", diagnosingBugs!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("diagnosing-bugs")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("diagnosing-bugs loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(diagnosingBugs!)
  expect(info.name).toBe("diagnosing-bugs")
  expect(info.content).toContain("# Diagnosing Bugs")
  expect(info.content).not.toContain("name: diagnosing-bugs")
})

test("diagnosing-bugs body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(diagnosingBugs!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/diagnosing-bugs/SKILL.md",
  )
  expect(body).toContain(
    "obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/systematic-debugging/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})
