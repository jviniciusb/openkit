import { expect, test } from "bun:test"
import { existsSync, readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const recipe = skills.find((s) => s.id === "skill-recipe")

test("skill-recipe is registered with autoinvoke:false", () => {
  expect(recipe).toBeDefined()
  expect(recipe!.autoinvoke).toBe(false)
})

test("skill-recipe SKILL.md frontmatter parses with name and description", () => {
  const text = readFileSync(new URL("SKILL.md", recipe!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("skill-recipe")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("skill-recipe loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(recipe!)
  expect(info.name).toBe("skill-recipe")
  expect(info.autoinvoke).toBe(false)
  expect(info.content).toContain("# Skill Recipe")
  expect(info.content).not.toContain("name: skill-recipe")
})

test("skill-recipe body is self-contained and carries the provenance format", () => {
  const info = loadSkill(recipe!)
  const body = info.content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain("license: MIT")
})

test("skill-recipe ships non-empty support files", () => {
  for (const file of ["rubric.md", "brief-template.md"]) {
    const path = new URL(file, recipe!.dir)
    expect(existsSync(path)).toBe(true)
    expect(readFileSync(path, "utf8").trim().length).toBeGreaterThan(0)
  }
})
