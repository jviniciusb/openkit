import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const diagnosingSessions = skills.find((s) => s.id === "diagnosing-sessions")

test("diagnosing-sessions is registered with autoinvoke:false", () => {
  expect(diagnosingSessions).toBeDefined()
  expect(diagnosingSessions!.autoinvoke).toBe(false)
})

test("diagnosing-sessions SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", diagnosingSessions!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("diagnosing-sessions")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("diagnosing-sessions loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(diagnosingSessions!)
  expect(info.name).toBe("diagnosing-sessions")
  expect(info.content).toContain("# Diagnosing Sessions")
  expect(info.content).not.toContain("name: diagnosing-sessions")
})

test("diagnosing-sessions body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(diagnosingSessions!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/diagnosing-superpowers/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("diagnosing-sessions requires citations and reports without mutating the environment", () => {
  const body = loadSkill(diagnosingSessions!).content
  expect(body).toContain("citation")
  expect(body).toContain("file:line")
  expect(body).toContain("Read-only")
  expect(body).toContain("Report, do not fix")
})
