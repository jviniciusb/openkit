import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const writingForAgents = skills.find((s) => s.id === "writing-for-agents")

test("writing-for-agents is registered and model-visible", () => {
  expect(writingForAgents).toBeDefined()
  expect(writingForAgents!.autoinvoke).toBeUndefined()
})

test("writing-for-agents SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", writingForAgents!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("writing-for-agents")
  expect(frontmatter.description).toBeTruthy()
})

test("writing-for-agents loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(writingForAgents!)
  expect(info.name).toBe("writing-for-agents")
  expect(info.content).toContain("# Writing for Agents")
  expect(info.content).not.toContain("name: writing-for-agents")
})

test("writing-for-agents body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(writingForAgents!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/productivity/writing-for-agents/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("writing-for-agents carries its core ideas", () => {
  const body = loadSkill(writingForAgents!).content
  expect(body).toContain("Progressive disclosure")
  expect(body).toContain("context pointer")
  expect(body).toContain("completion criterion")
  expect(body).toContain("leading word")
})
