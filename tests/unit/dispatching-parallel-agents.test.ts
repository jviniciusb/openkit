import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const skill = skills.find((s) => s.id === "dispatching-parallel-agents")

test("dispatching-parallel-agents is registered and model-visible", () => {
  expect(skill).toBeDefined()
  expect(skill!.autoinvoke).toBeUndefined()
})

test("dispatching-parallel-agents SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", skill!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("dispatching-parallel-agents")
  expect(frontmatter.description).toBeTruthy()
})

test("dispatching-parallel-agents loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(skill!)
  expect(info.name).toBe("dispatching-parallel-agents")
  expect(info.content).toContain("# Dispatching Parallel Agents")
  expect(info.content).not.toContain("name: dispatching-parallel-agents")
})

test("dispatching-parallel-agents body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(skill!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/dispatching-parallel-agents/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("dispatching-parallel-agents dispatches the authorized ready set together", () => {
  const body = loadSkill(skill!).content
  expect(body).toContain("actively check whether two or more ready pieces")
  expect(body).toContain("dispatch all of them in the same response")
  expect(body).toContain("Do not send one subagent at a time")
  expect(body).toContain("batched tool calls")
  expect(body).toContain("Never dispatch work across an approval gate")
})

test("dispatching-parallel-agents keeps the do-not-parallelize guard", () => {
  const body = loadSkill(skill!).content
  expect(body).toContain("shared state")
  expect(body).toContain("Do not parallelize")
  expect(body).toContain("A task depends on unfinished work")
  expect(body).toContain("Independently scoped investigations may proceed concurrently")
})
