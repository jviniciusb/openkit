import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const verification = skills.find((s) => s.id === "verification")

test("verification is registered and model-visible", () => {
  expect(verification).toBeDefined()
  expect(verification!.autoinvoke).toBeUndefined()
})

test("verification SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", verification!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("verification")
  expect(frontmatter.description).toBeTruthy()
})

test("verification loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(verification!)
  expect(info.name).toBe("verification")
  expect(info.content).toContain("# Verification")
  expect(info.content).not.toContain("name: verification")
})

test("verification body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(verification!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/verification-before-completion/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("verification requires evidence from the current tree", () => {
  const body = loadSkill(verification!).content
  expect(body).toContain("current tree")
})
