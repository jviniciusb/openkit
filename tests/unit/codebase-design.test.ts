import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const codebaseDesign = skills.find((s) => s.id === "codebase-design")

test("codebase-design is registered and model-visible", () => {
  expect(codebaseDesign).toBeDefined()
  expect(codebaseDesign!.autoinvoke).toBeUndefined()
})

test("codebase-design SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", codebaseDesign!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("codebase-design")
  expect(frontmatter.description).toBeTruthy()
})

test("codebase-design loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(codebaseDesign!)
  expect(info.name).toBe("codebase-design")
  expect(info.content).toContain("# Codebase Design")
  expect(info.content).not.toContain("name: codebase-design")
})

test("codebase-design body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(codebaseDesign!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/codebase-design/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("codebase-design keeps the deep-module vocabulary and the seam rule", () => {
  const body = loadSkill(codebaseDesign!).content
  expect(body).toContain("seam")
  expect(body).toContain("interface")
  expect(body).toContain("depth")
  expect(body).toContain("locality")
  expect(body).toContain("One adapter means a hypothetical seam")
})
