import { expect, test } from "bun:test"
import { existsSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill } from "../../src/core/skill"
import { tools } from "../../src/tools/index"

test("ships the seven expected skills with unique ids across tools and skills", () => {
  expect(skills.map((s) => s.id)).toEqual([
    "skill-recipe",
    "english-writing-assistant",
    "sdd-flow",
    "interview",
    "research",
    "handoff",
    "code-review",
  ])
  const ids = [...tools.map((t) => t.id), ...skills.map((s) => s.id)]
  expect(new Set(ids).size).toBe(ids.length)
})

test("skill-recipe registers autoinvoke:false with a real directory and resolvable files", () => {
  const skill = skills.find((s) => s.id === "skill-recipe")!
  const info = loadSkill(skill)
  expect(info.autoinvoke).toBe(false)
  for (const file of ["SKILL.md", "rubric.md", "brief-template.md"]) {
    expect(existsSync(new URL(file, skill.dir))).toBe(true)
  }
})

test("english-writing-assistant parses its folded description and is model-visible", () => {
  const info = loadSkill(skills.find((s) => s.id === "english-writing-assistant")!)
  expect(info.description).toContain("Brazilian Portuguese")
  expect(info.description).not.toContain(">-")
  expect("autoinvoke" in info).toBe(false)
})

test("interview parses its description and is model-visible", () => {
  const info = loadSkill(skills.find((s) => s.id === "interview")!)
  expect(info.description).toBeTruthy()
  expect("autoinvoke" in info).toBe(false)
})

test("sdd-flow registers autoinvoke:false with a real directory and resolvable files", () => {
  const skill = skills.find((s) => s.id === "sdd-flow")!
  const info = loadSkill(skill)
  expect(info.autoinvoke).toBe(false)
  expect(info.content).toContain("# SDD Flow")
  expect(info.content).not.toContain("name: sdd-flow")
  expect(info.content).toContain("\n---\n")
  for (const file of ["SKILL.md", "spec-template.md", "step-format.md"]) {
    expect(existsSync(new URL(file, skill.dir))).toBe(true)
  }
  expect(existsSync(new URL("update-refs.sh", skill.dir))).toBe(false)
})

test("sdd-flow body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(skills.find((s) => s.id === "sdd-flow")!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).not.toContain("Explore")
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/subagent-driven-development/SKILL.md",
  )
  expect(body).toContain(
    "mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/implement-spec/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})
