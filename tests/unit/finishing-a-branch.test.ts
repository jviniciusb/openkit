import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const finishing = skills.find((s) => s.id === "finishing-a-branch")

test("finishing-a-branch is registered with autoinvoke:false", () => {
  expect(finishing).toBeDefined()
  expect(finishing!.autoinvoke).toBe(false)
})

test("finishing-a-branch SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", finishing!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("finishing-a-branch")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("finishing-a-branch loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(finishing!)
  expect(info.name).toBe("finishing-a-branch")
  expect(info.content).toContain("# Finishing a Branch")
  expect(info.content).not.toContain("name: finishing-a-branch")
})

test("finishing-a-branch body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(finishing!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/finishing-a-development-branch/SKILL.md",
  )
  expect(body).toContain(
    "mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/pr/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("finishing-a-branch requires a typed confirmation to discard", () => {
  const body = loadSkill(finishing!).content
  expect(body).toContain("discard")
  expect(body).toMatch(/typed confirmation/i)
})
