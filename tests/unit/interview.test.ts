import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const interview = skills.find((s) => s.id === "interview")

test("interview is registered and model-visible", () => {
  expect(interview).toBeDefined()
  expect(interview!.autoinvoke).toBeUndefined()
})

test("interview SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", interview!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("interview")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("interview loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(interview!)
  expect(info.name).toBe("interview")
  expect(info.content).toContain("# Interview")
  expect(info.content).not.toContain("name: interview")
})

test("interview body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(interview!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain("from: obra/superpowers@v7.0.0 skills/brainstorming/SKILL.md")
  expect(body).toContain("mattpocock/skills@v1.3.1 skills/productivity/grilling/SKILL.md")
  expect(body).toContain("license: MIT")
})
