import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const retro = skills.find((s) => s.id === "retro")

test("retro is registered with autoinvoke:false", () => {
  expect(retro).toBeDefined()
  expect(retro!.autoinvoke).toBe(false)
})

test("retro SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", retro!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("retro")
  expect(frontmatter.description).toBeTruthy()
  expect(frontmatter.description).not.toContain(">-")
})

test("retro loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(retro!)
  expect(info.name).toBe("retro")
  expect(info.content).toContain("# Retro")
  expect(info.content).not.toContain("name: retro")
})

test("retro body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(retro!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/retro/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("retro proposes changes and requires no tracker", () => {
  const body = loadSkill(retro!).content
  expect(body).toContain("Proposed, not applied")
  expect(body).toContain("No tracker required")
})
