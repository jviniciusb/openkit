import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const handoff = skills.find((s) => s.id === "handoff")

test("handoff is registered with autoinvoke false", () => {
  expect(handoff).toBeDefined()
  expect(handoff!.autoinvoke).toBe(false)
})

test("handoff SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", handoff!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("handoff")
  expect(frontmatter.description).toBeTruthy()
})

test("handoff loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(handoff!)
  expect(info.name).toBe("handoff")
  expect(info.content).toContain("# Handoff")
  expect(info.content).not.toContain("name: handoff")
})

test("handoff body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(handoff!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/productivity/handoff/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("handoff body carries the portable-output rule and forbids dev-only locations", () => {
  const body = loadSkill(handoff!).content
  // A user-named path wins; otherwise a gitignored or temporary location.
  expect(body).toMatch(/user[- ]named path/i)
  expect(body).toMatch(/gitignored or temporary/i)
  // It must never instruct writing into skill-sources/ or any tracked path.
  expect(body).toMatch(/never the repository root, `skill-sources\/`, or any tracked path/i)
  expect(body).not.toMatch(/otherwise use the repository or workspace root/i)
})
