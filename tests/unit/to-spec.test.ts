import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const toSpec = skills.find((s) => s.id === "to-spec")

test("to-spec is registered with autoinvoke:false", () => {
  expect(toSpec).toBeDefined()
  expect(toSpec!.autoinvoke).toBe(false)
})

test("to-spec SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", toSpec!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("to-spec")
  expect(frontmatter.description).toBeTruthy()
})

test("to-spec loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(toSpec!)
  expect(info.name).toBe("to-spec")
  expect(info.content).toContain("# To Spec")
  expect(info.content).not.toContain("name: to-spec")
})

test("to-spec body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(toSpec!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/to-spec/SKILL.md",
  )
  expect(body).toContain("license: MIT")
})

test("to-spec preserves decisions and writes where the user says", () => {
  const body = loadSkill(toSpec!).content
  expect(body).toContain("Open questions")
  expect(body).toContain("No new requirements are gathered")
  expect(body).toContain("lands at the path the user named")
})
