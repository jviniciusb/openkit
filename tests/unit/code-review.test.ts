import { expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { skills } from "../../src/skills/index"
import { loadSkill, readSkillFrontmatter } from "../../src/core/skill"

const codeReview = skills.find((s) => s.id === "code-review")

test("code-review is registered and model-visible", () => {
  expect(codeReview).toBeDefined()
  expect(codeReview!.autoinvoke).toBeUndefined()
})

test("code-review SKILL.md frontmatter parses with name and a description", () => {
  const text = readFileSync(new URL("SKILL.md", codeReview!.dir), "utf8")
  const frontmatter = readSkillFrontmatter(text)
  expect(frontmatter.name).toBe("code-review")
  expect(frontmatter.description).toBeTruthy()
})

test("code-review loads through loadSkill with stripped frontmatter", () => {
  const info = loadSkill(codeReview!)
  expect(info.name).toBe("code-review")
  expect(info.content).toContain("# Code Review")
  expect(info.content).not.toContain("name: code-review")
})

test("code-review body is self-contained and carries the provenance comment", () => {
  const body = loadSkill(codeReview!).content
  expect(body).not.toMatch(/superpowers:/)
  expect(body).not.toMatch(/mattpocock-skills:/)
  expect(body).toContain("<!-- generated by skill-recipe")
  expect(body).toContain(
    "from: mattpocock/skills@24fe0ef7737efae15c87225755e9f6f5965e4888 skills/engineering/code-review/SKILL.md",
  )
  expect(body).toContain("obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/requesting-code-review/SKILL.md")
  expect(body).toContain("obra/superpowers@bb92a77741419a4ab5f06e711a283343f1ada0c3 skills/receiving-code-review/SKILL.md")
  expect(body).toContain("license: MIT")
})
